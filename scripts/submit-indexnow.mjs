import {readFile,writeFile} from 'node:fs/promises';
import { sitemapBatches, submitBatches } from './indexnow-batches.mjs';
const config=JSON.parse(await readFile(new URL('../docs/indexnow-config.json',import.meta.url),'utf8'));
const keyResponse=await fetch(config.keyLocation,{headers:{"user-agent":"Mozilla/5.0 TilingSiteVerification"}});
if(!keyResponse.ok||(await keyResponse.text()).trim()!==config.key)throw new Error('Published IndexNow ownership file does not match');
const sitemapResponse=await fetch(`https://${config.host}/sitemap.xml`,{headers:{"user-agent":"Mozilla/5.0 TilingSiteVerification"}});
if(!sitemapResponse.ok)throw new Error('Cannot read published sitemap');
const xml=await sitemapResponse.text();
const batches=sitemapBatches(xml,config.host);
const results=await submitBatches(config,batches);
const complete=results.length===batches.length&&results.every(result=>result.accepted);
const receipt={submittedAt:new Date().toISOString(),host:config.host,urlCount:batches.flat().length,batchCount:batches.length,acceptedUrlCount:results.filter(r=>r.accepted).reduce((sum,r)=>sum+r.urlCount,0),complete,results,meaning:complete?'URLs received; a 202 batch still requires key validation. Indexing is not guaranteed.':'Submission incomplete. Inspect batch receipts before resubmitting.'};
if(process.argv[2])await writeFile(process.argv[2],JSON.stringify(receipt,null,2)+'\n');
console.log(JSON.stringify(receipt));
if(!complete)process.exitCode=1;
